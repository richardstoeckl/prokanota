def test_crispr_array_geometry_is_consistent():
    """
    Verify the internal geometry of every predicted CRISPR array.

    A biological CRISPR array must contain at least two repeats. Its reported
    length must equal the inclusive genomic interval, and that interval should
    be explained by the repeat lengths plus the intervening spacers. The small
    tolerance accounts for integer reporting of the average spacer length.
    """
    path = RESULTS_DIR / GENOME_SAMPLE / "features" / f"{GENOME_SAMPLE}_crispr.tsv"
    for row in parse_tsv_rows(path):
        start = int(row["start"])
        end = int(row["end"])
        length = int(row["length"])
        repeat_length = int(row["repeat_length"])
        spacer_length = int(row["spacer_length"])
        repeat_count = int(row["num_repeats"])

        assert repeat_count >= 2
        assert length == end - start + 1
        inferred_length = (repeat_count * repeat_length) + (
            (repeat_count - 1) * spacer_length
        )
        assert abs(length - inferred_length) <= repeat_count - 1


