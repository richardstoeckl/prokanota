# Raw search tools do not all emit rows in a deterministic order. This helper
# parses, optionally filters, sorts, and serializes tables into a stable form
# before comparison. It prevents harmless row-order differences from masking
# genuine changes in columns or values.
def normalize_tsv(
    path: Path,
    sort_key_col: str | int = "gene_id",
    column_filter=None,
    delimiter: str = "\t",
    line_parser=None,
    has_header: bool = True,
) -> str:
    raw_lines = path.read_text().splitlines()
    data_lines = [
        line.strip() for line in raw_lines if line.strip() and not line.startswith("#")
    ]
    if not data_lines:
        return ""

    if line_parser is not None:
        rows = [line_parser(line) for line in data_lines]
    else:
        rows = [line.split(delimiter) for line in data_lines]

    if has_header:
        header_columns = rows[0]
        data_rows = rows[1:]
    else:
        header_columns = []
        data_rows = rows

    if column_filter is not None and header_columns:
        keep_indexes = column_filter(header_columns)
    else:
        keep_indexes = list(range(len(header_columns))) if header_columns else []

    if header_columns:
        filtered_header = [header_columns[index] for index in keep_indexes]
        rows_to_sort = [[row[index] for index in keep_indexes] for row in data_rows]
    else:
        filtered_header = []
        rows_to_sort = data_rows

    if not rows_to_sort:
        sorted_rows = []
    elif isinstance(sort_key_col, int):
        sort_index = min(sort_key_col, len(rows_to_sort[0]) - 1)
        sorted_rows = sorted(rows_to_sort, key=lambda row: row[sort_index])
    elif sort_key_col in filtered_header:
        sort_index = filtered_header.index(sort_key_col)
        sorted_rows = sorted(rows_to_sort, key=lambda row: row[sort_index])
    else:
        sorted_rows = sorted(rows_to_sort, key=lambda row: row[0])

    normalized_rows = ["\t".join(row) for row in sorted_rows]
    if filtered_header:
        return "\n".join(["\t".join(filtered_header), *normalized_rows]).strip()
    return "\n".join(normalized_rows).strip()


def normalize_tblout(path: Path) -> str:
    """
    Normalize PyHMMER's whitespace-delimited internal hit table.

    Unlike the other search tools, PyHMMER does not emit a conventional TSV,
    so rows are split on whitespace and sorted by the target gene identifier.
    """
    return normalize_tsv(
        path,
        sort_key_col=0,
        line_parser=lambda line: line.split(maxsplit=18),
        has_header=False,
    )


def normalize_annotation(path: Path) -> str:
    """
    Normalize a final annotation table for the active database test mode.

    Expected full-mode fixtures contain columns for every test database.
    During pyhmmer-only testing, columns belonging exclusively to disabled
    databases are removed before comparison; all shared biological columns
    and enabled PyHMMER columns are still compared exactly.
    """

    def column_filter(header_columns):
        return [
            index
            for index, column in enumerate(header_columns)
            if column in ENABLED_DB_COLUMNS or column not in ALL_DB_COLUMNS
        ]

    return normalize_tsv(
        path,
        sort_key_col="gene_id",
        column_filter=column_filter,
    )


def assert_files_equal(actual: Path, expected: Path, normalizer=None) -> None:
    """Compare a generated file with its committed regression fixture."""
    assert expected.exists(), f"Missing expected file: {expected}"
    assert actual.exists(), f"Missing generated file: {actual}"

    if normalizer is None:
        actual_text = actual.read_text(encoding="utf-8", errors="replace")
        expected_text = expected.read_text(encoding="utf-8", errors="replace")
    else:
        actual_text = normalizer(actual)
        expected_text = normalizer(expected)

    if actual_text != expected_text:
        diff = "\n".join(
            difflib.unified_diff(
                expected_text.splitlines(),
                actual_text.splitlines(),
                fromfile=str(expected),
                tofile=str(actual),
                lineterm="",
            )
        )
        pytest.fail(diff)


def assert_directories_equal(actual: Path, expected: Path, normalizer=None) -> None:
    """
    Compare directory structure and every contained output file.

    This catches missing outputs, unexpected extra outputs, and changes in
    file contents rather than checking only a few hand-picked records.
    """
    assert expected.exists(), f"Missing expected directory: {expected}"
    assert actual.exists(), f"Missing generated directory: {actual}"

    expected_files = {
        path.relative_to(expected) for path in expected.rglob("*") if path.is_file()
    }
    actual_files = {
        path.relative_to(actual) for path in actual.rglob("*") if path.is_file()
    }
    assert actual_files == expected_files, (
        f"Directory contents differ; missing={sorted(expected_files - actual_files)}, "
        f"extra={sorted(actual_files - expected_files)}"
    )

    for relative_path in sorted(expected_files):
        selected_normalizer = (
            normalizer
            if normalizer is not None and relative_path.suffix == ".tsv"
            else None
        )
        assert_files_equal(
            actual / relative_path,
            expected / relative_path,
            normalizer=selected_normalizer,
        )


def parse_fasta(path: Path) -> dict[str, str]:
    """Parse FASTA records by their first header token for cross-format checks."""
    assert path.exists(), f"Missing FASTA: {path}"
    records = {}
    current_id = None
    current_sequence = []
    for line in path.read_text().splitlines():
        if line.startswith(">"):
            if current_id is not None:
                records[current_id] = "".join(current_sequence)
            current_id = line[1:].split()[0]
            current_sequence = []
        elif line.strip():
            current_sequence.append(line.strip())
    if current_id is not None:
        records[current_id] = "".join(current_sequence)
    return records


def parse_gff_features(path: Path) -> list[list[str]]:
    """
    Parse GFF3 feature rows.

    Headers, comments, and any trailing embedded FASTA section are ignored.
    Every biological feature must have the nine columns required by GFF3.
    """
    assert path.exists(), f"Missing GFF: {path}"
    features = []
    for line in path.read_text().splitlines():
        if line.startswith("##FASTA") or line.startswith(">"):
            break
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        assert len(fields) == 9, f"Invalid GFF row in {path}: {line}"
        features.append(fields)
    return features


def parse_tsv_rows(path: Path) -> list[dict[str, str]]:
    """Load a tabular output into dictionaries keyed by the header names."""
    assert path.exists(), f"Missing TSV: {path}"
    lines = [line for line in path.read_text().splitlines() if line.strip()]
    if not lines:
        return []
    header = lines[0].split("\t")
    rows = []
    for line in lines[1:]:
        fields = line.split("\t")
        assert len(fields) == len(header), f"Invalid TSV row in {path}: {line}"
        rows.append(dict(zip(header, fields, strict=True)))
    return rows


def normalize_sequence(sequence: str) -> str:
    """Remove formatting whitespace and normalize reference sequences to uppercase."""
    return "".join(character for character in sequence if character.isalpha()).upper()


def extract_gbk_translation(path: Path, locus_tag: str) -> str:
    """
    Extract a possibly wrapped GenBank ``/translation`` qualifier.

    GenBank wraps long protein sequences over multiple indented lines, so the
    parser continues until the closing quote belonging to the requested locus.
    """
    lines = path.read_text().splitlines()
    for index, line in enumerate(lines):
        if f'/locus_tag="{locus_tag}"' not in line:
            continue
        for translation_index in range(index, len(lines)):
            translation_line = lines[translation_index]
            if '/translation="' not in translation_line:
                continue
            fragment = translation_line.split('/translation="', 1)[1]
            parts = [fragment]
            if '"' in fragment:
                return normalize_sequence(fragment.split('"', 1)[0])
            for continuation in lines[translation_index + 1 :]:
                chunk = continuation.strip()
                if '"' in chunk:
                    parts.append(chunk.split('"', 1)[0])
                    return normalize_sequence("".join(parts))
                parts.append(chunk)
        break
    return ""


