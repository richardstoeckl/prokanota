# Load the same database registry selected by the runner. The selected database
# names determine which raw/parsed outputs must exist and which annotation
# columns are expected in pyhmmer-only versus full testing mode.
def load_databases(path: Path, enabled_only: bool = False) -> list[dict[str, object]]:
    data = yaml.safe_load(path.read_text())
    databases = data.get("databases") if isinstance(data, dict) else None
    if not isinstance(databases, list):
        raise ValueError(f"Invalid databases file {path}: missing databases list")
    return [
        database
        for database in databases
        if isinstance(database, dict)
        and (not enabled_only or database.get("enabled", True))
    ]


