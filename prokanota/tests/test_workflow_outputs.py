# 4. GFF3 Structural Validation
# ---

# GFF3 uses one-based inclusive coordinates. Starts and ends must therefore be
# positive integers with start <= end. The strand column is restricted by the
# GFF3 format, and CRISPR repeat_region features are intentionally unstranded.


@pytest.mark.parametrize("sample_id", SAMPLES)
def test_gff_coordinates_are_valid(sample_id):
    """Verify that every GFF3 feature has a valid one-based interval."""
    gff_path = RESULTS_DIR / sample_id / "features" / f"{sample_id}.gff"
    for fields in parse_gff_features(gff_path):
        start = int(fields[3])
        end = int(fields[4])
        assert start >= 1 and end >= start


@pytest.mark.parametrize("sample_id", SAMPLES)
def test_gff_strands_are_valid(sample_id):
    """Verify GFF3 strand symbols and unstranded CRISPR regions."""
    gff_path = RESULTS_DIR / sample_id / "features" / f"{sample_id}.gff"
    for fields in parse_gff_features(gff_path):
        if fields[2] == "repeat_region":
            assert fields[6] == "."
        else:
            assert fields[6] in ("+", "-", ".", "?")


